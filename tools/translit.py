# -*- coding: utf-8 -*-
LOW = {'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'e','ж':'j','з':'z',
       'и':'i','й':'=','к':'k','л':'l','м':'m','н':'n','о':'o','п':'p','р':'r',
       'с':'s','т':'t','у':'y','ф':'f','х':'x','ц':'c','ч':'h','ш':'w','щ':'{',
       'ъ':'|','ы':'#','ь':'}','э':'&','ю':'u','я':'q'}
UP = {'А':'A','Б':'B','В':'V','Г':'G','Д':'D','Е':'E','Ё':'E','Ж':'J','З':'Z',
      'И':'I','Й':'=','К':'K','Л':'L','М':'M','Н':'N','О':'O','П':'P','Р':'R',
      'С':'S','Т':'T','У':'Y','Ф':'F','Х':'X','Ц':'C','Ч':'H','Ш':'W','Щ':'{',
      'Ъ':'|','Ы':'#','Ь':'}','Э':'>','Ю':'U','Я':'Q'}
MAP = {}
MAP.update(LOW)
MAP.update(UP)
MAP.update({'«':'','»':'','“':'','„':'','—':'-','–':'-','…':'...','№':'No'})

unmapped = set()

def enc(s):
    out = []
    for ch in s:
        if ch in MAP:
            out.append(MAP[ch])
        elif 32 <= ord(ch) <= 126:
            out.append(ch)
        else:
            unmapped.add(ch)
            out.append('?')
    return ''.join(out).encode('latin1')

